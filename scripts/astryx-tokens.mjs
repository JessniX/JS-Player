// Copies Astryx's non-colour design tokens out of @astryxdesign/core into src/astryx-tokens.css.
// JS Player is plain HTML/JS (no React), so it uses Astryx tokens only, not its components.
// Colours stay with JS Player's own theme editor. Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';


const pkgDir = fileURLToPath(new URL('../node_modules/@astryxdesign/core/', import.meta.url));
const { version } = JSON.parse(readFileSync(pkgDir + 'package.json', 'utf8'));
const css = readFileSync(pkgDir + 'dist/astryx.css', 'utf8');

const KEEP = /^--(spacing|radius|shadow-(low|med|high)$|duration|ease|font-size|font-weight|focus-outline-(width|style|offset)$|size-element|border-width$)/;
const tokens = new Map();
for (const [, selector, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  if (!selector.trim().startsWith(':root')) continue;
  for (const [, name, value] of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+)/g)) {
    if (KEEP.test(name) && !tokens.has(name)) tokens.set(name, value.trim());
  }
}
if (tokens.size < 40) throw new Error(`Only found ${tokens.size} tokens; the astryx.css layout may have changed.`);

const lines = [...tokens].map(([k, v]) => `  ${k}: ${v};`).join('\n');
writeFileSync(new URL('../src/astryx-tokens.css', import.meta.url),
  `/* Generated by scripts/astryx-tokens.mjs from @astryxdesign/core ${version}. Do not edit; run npm run tokens. */\n:root {\n${lines}\n}\n`);
console.log(`Wrote ${tokens.size} Astryx tokens (core ${version}) to src/astryx-tokens.css`);
