const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('prism', {
  openFiles: () => ipcRenderer.invoke('open-files'),
  openFolder: () => ipcRenderer.invoke('open-folder'),
  expandPaths: (paths) => ipcRenderer.invoke('expand-paths', paths),
  openSubtitle: () => ipcRenderer.invoke('open-subtitle'),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  readText: (p) => ipcRenderer.invoke('read-text', p),
  findSidecarSubs: (p) => ipcRenderer.invoke('find-sidecar-subs', p),
  probe: (p) => ipcRenderer.invoke('probe', p),
  transcode: (p) => ipcRenderer.invoke('transcode', p),
  cancelTranscode: () => ipcRenderer.invoke('cancel-transcode'),
  onTranscodeProgress: (cb) => ipcRenderer.on('transcode-progress', (_e, v) => cb(v)),
  imageSiblings: (p) => ipcRenderer.invoke('image-siblings', p),
  convertImage: (p) => ipcRenderer.invoke('convert-image', p),
  thumb: (p) => ipcRenderer.invoke('thumb', p),
  fileStat: (p) => ipcRenderer.invoke('file-stat', p),
  feedsStatus: () => ipcRenderer.invoke('feeds-status'),
  feedsSignOut: (id) => ipcRenderer.invoke('feeds-sign-out', id),
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateStatus: (cb) => ipcRenderer.on('update-status', (_e, s) => cb(s)),
  feedsFetchIcon: (url) => ipcRenderer.invoke('feeds-fetch-icon', url),
  readImageDataUrl: (p) => ipcRenderer.invoke('read-image-dataurl', p),
  feedsClearSite: (url) => ipcRenderer.invoke('feeds-clear-site', url),
  addonFetch: (url, as) => ipcRenderer.invoke('addon-fetch', url, as),
  stremioServer: (base) => ipcRenderer.invoke('stremio-server', base),
  stremioInstalled: () => ipcRenderer.invoke('stremio-installed'),
  stremioServerEnsure: (base) => ipcRenderer.invoke('stremio-server-ensure', base),
  stremioServerCreate: (base, hash, sources) => ipcRenderer.invoke('stremio-server-create', base, hash, sources),
  stremioServerRemove: (base, hash) => ipcRenderer.invoke('stremio-server-remove', base, hash),
  remoteUrl: (u, headers) => 'prism://app/remote?u=' + encodeURIComponent(u) + (headers ? '&h=' + encodeURIComponent(JSON.stringify(headers)) : ''),
  torrentStart: (args) => ipcRenderer.invoke('torrent-start', args),
  torrentStatus: () => ipcRenderer.invoke('torrent-status'),
  torrentStop: () => ipcRenderer.invoke('torrent-stop'),
  torrentOptions: (o) => ipcRenderer.invoke('torrent-options', o),
  streamPlan: (url, headers) => ipcRenderer.invoke('stream-plan', url, headers),
  liveCreate: (o) => ipcRenderer.invoke('live-create', o),
  liveStop: () => ipcRenderer.invoke('live-stop'),
  liveKeyframe: (id, t) => ipcRenderer.invoke('live-keyframe', id, t),
  subsConvert: (url, headers) => ipcRenderer.invoke('subs-convert', url, headers),
  subsExtract: (o) => ipcRenderer.invoke('subs-extract', o),
  subsStop: () => ipcRenderer.invoke('subs-stop'),
  onSubsChunk: (cb) => ipcRenderer.on('subs-chunk', (_e, m) => cb(m)),
  stremioAccount: () => ipcRenderer.invoke('stremio-account'),
  stremioLogin: (email, password) => ipcRenderer.invoke('stremio-login', email, password),
  stremioLogout: () => ipcRenderer.invoke('stremio-logout'),
  stremioAddonsGet: () => ipcRenderer.invoke('stremio-addons-get'),
  stremioAddonsSet: (addons) => ipcRenderer.invoke('stremio-addons-set', addons),
  stremioLibraryGet: () => ipcRenderer.invoke('stremio-library-get'),
  stremioLibraryPut: (changes) => ipcRenderer.invoke('stremio-library-put', changes),
  onFeedEscape: (cb) => ipcRenderer.on('feed-escape', () => cb()),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (s) => ipcRenderer.send('save-settings', s),
  getLaunchFiles: () => ipcRenderer.invoke('get-launch-files'),
  onOpenFiles: (cb) => ipcRenderer.on('open-files', (_e, f) => cb(f)),
  saveScreenshot: (dataUrl, name) => ipcRenderer.invoke('save-screenshot', dataUrl, name),
  exportTheme: (t) => ipcRenderer.invoke('export-theme', t),
  importTheme: () => ipcRenderer.invoke('import-theme'),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  openCache: () => ipcRenderer.invoke('open-cache'),
  clearCache: () => ipcRenderer.invoke('clear-cache'),
  ffmpegStatus: () => ipcRenderer.invoke('ffmpeg-status'),
  windowCmd: (cmd, arg) => ipcRenderer.send('window', cmd, arg),
  pathForFile: (file) => webUtils.getPathForFile(file),
  mediaUrl: (p) => 'prism://app/media?p=' + encodeURIComponent(p),
  platform: process.platform,
});
